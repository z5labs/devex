package planner

import (
	"strconv"
	"strings"
)

// jenkinsPreamble heads every Jenkins render. It is a comment, so it does not
// change what the script evaluates to, and it carries the consumption path with
// the artifact rather than only in a README the plan will be read without.
const jenkinsPreamble = `// Generated by workspace-ci. This script evaluates to a Map of stage name to
// closure, which is exactly what Jenkins' parallel step takes:
//
//   stage('run') {
//     steps {
//       sh 'dagger -m github.com/z5labs/devex/daggerverse/workspace-ci call plan' +
//          " --base=$BASE_SHA --head=$HEAD_SHA --format=JENKINS > plan.groovy"
//       script { parallel load('plan.groovy') }
//     }
//   }
//
// Each branch runs one leg's checks on the pipeline's own agent, bounded by that
// leg's step budget. An empty plan evaluates to [:], which parallel accepts as a
// no-op — [] would be an empty List and parallel would reject it.
`

// renderJenkins emits a plan as Groovy: a map literal of leg name to a closure
// that runs that leg.
//
// A closure is the one thing a plan cannot be serialized as, which is why this
// format exists at all. Jenkins' parallel step takes Map<String, Closure> and
// nothing else, so any JSON form of a plan has to be turned into closures by a
// consumer's own collectEntries — the shim this removes.
func renderJenkins(entries []Entry) string {
	var b strings.Builder
	b.WriteString(jenkinsPreamble)
	if len(entries) == 0 {
		b.WriteString("[:]\n")
		return b.String()
	}
	b.WriteString("[\n")
	for i, e := range entries {
		if i > 0 {
			b.WriteString(",\n")
		}
		b.WriteString(jenkinsBranch(e))
	}
	b.WriteString("\n]\n")
	return b.String()
}

// jenkinsBranch renders one leg as a `'<name>': { … }` map entry.
//
// The body is a `stage` so the branch is named in the stage view rather than
// appearing as an anonymous parallel arm, wrapped in the leg's `timeout` so a
// stuck check fails its own branch instead of the whole pipeline's cap. It
// allocates no `node`: the pipeline's own `agent` directive already decided
// where work runs, and an emitted `node` would both override that choice and
// need a checkout of its own.
//
// JobTimeout has no analogue here — a branch has no surrounding job to bound —
// so it is not rendered.
func jenkinsBranch(e Entry) string {
	name := groovyString(e.Name)
	body := []string{"sh " + groovyString(checkCommand(e))}
	// A non-positive budget is an unapplied one (Timeouts.Apply never produces
	// one). `timeout(time: 0)` aborts the branch immediately, so render no
	// timeout at all rather than one that fails everything.
	if e.Timeout > 0 {
		body = []string{
			"timeout(time: " + strconv.Itoa(e.Timeout) + ", unit: 'MINUTES') {",
			"  " + body[0],
			"}",
		}
	}
	lines := []string{
		name + ": {",
		"  stage(" + name + ") {",
	}
	for _, l := range body {
		lines = append(lines, "    "+l)
	}
	lines = append(lines, "  }", "}")
	for i, l := range lines {
		lines[i] = "  " + l
	}
	return strings.Join(lines, "\n")
}

// checkCommand is the shell command a leg runs: the same `-m <module>` plus
// check pattern every other format hands to a CI system, assembled here because
// a closure with no body drives nothing.
//
// An empty filter means "every check this module has", which `dagger check` with
// no pattern already does.
func checkCommand(e Entry) string {
	cmd := "dagger -m " + shellQuote(e.Module) + " check"
	if e.Filter != "" {
		cmd += " " + shellQuote(e.Filter)
	}
	return cmd
}

// groovyString renders s as a Groovy single-quoted literal. Single-quoted is
// what makes it a plain String rather than a GString, so a `$` in a module path
// is a dollar sign and not an interpolation of an undefined variable.
func groovyString(s string) string {
	r := strings.NewReplacer(
		`\`, `\\`,
		`'`, `\'`,
		"\n", `\n`,
		"\r", `\r`,
		"\t", `\t`,
	)
	return "'" + r.Replace(s) + "'"
}

// shellQuote renders s as a POSIX single-quoted word. A single quote cannot be
// escaped inside one, so it is closed, escaped and reopened.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
