// sdkGenerated is Generated for a workspace whose config installs its SDKs.
//
// There the SDK module already owns the comparison: it declares a staleness check
// of its own (github.com/dagger/go-sdk's is `stale`), which regenerates every
// module and client it manages and fails when the committed tree differs —
// bindings and module manifests alike. Plan gives that check a leg in every plan
// (see installedLegs), so running a second sweep here would pay for the same
// codegen twice. What is left for this check is the two guarantees that make a
// green staleness check mean something:
//
//   - It looked at everything. Every committed generated file must belong to a
//     module some SDK manages, found by globbing for the files rather than by
//     asking the SDK. A module left out of every SDK scope is generated by
//     nobody, and turns this red instead of disappearing from a green run.
//   - It can fail. The Go SDK's staleness check is run against a bare module of
//     this check's own, once as generated, where it must pass, and once with that
//     module's bindings made stale, where it must fail.
//
// A workspace configured by dagger.json alone installs no SDK, and gets the sweep.
func sdkGenerated(ctx context.Context, ws *dagger.Workspace, sdks []dagger.WorkspaceSDK) error {
	var modules []string
	var goSDK *dagger.WorkspaceSDK
	for i := range sdks {
		name, err := sdks[i].Name(ctx)
		if err != nil {
			return fmt.Errorf("read an installed SDK's name: %w", err)
		}
		if name == probeSDK {
			goSDK = &sdks[i]
		}
		managed, err := sdks[i].Modules(ctx)
		if err != nil {
			return fmt.Errorf("list the modules SDK %q manages: %w", name, err)
		}
		for j := range managed {
			src, err := managed[j].Source(ctx)
			if err != nil {
				return fmt.Errorf("read the source of a module SDK %q manages: %w", name, err)
			}
			dir := path.Clean(strings.TrimPrefix(src, "/"))
			if dir == "" {
				dir = "."
			}
			modules = append(modules, dir)
		}
	}
	if len(modules) == 0 {
		return fmt.Errorf("the workspace installs SDKs but none of them manages a module: a check that verified nothing would pass")
	}
	if goSDK == nil {
		return fmt.Errorf("the workspace installs no %q SDK, and the proof that a staleness check can fail is written in Go", probeSDK)
	}

	sources := make(map[string]*dagger.ModuleSource, len(modules))
	for _, dir := range modules {
		sources[dir] = moduleSource(ws, dir)
	}
	if err := sweptEverything(ctx, ws, modules, sources, unsweptBySDK); err != nil {
		return err
	}
	pin, err := sources[modules[0]].EngineVersion(ctx)
	if err != nil {
		return fmt.Errorf("read the engine version to build the stale-module proof at: %w", err)
	}
	return sdkStaleIsReported(ctx, ws, goSDK, pin)
}

// probeSDK is the SDK the stale-module proof is written for: the probe module is
// Go source.
const probeSDK = "go"

// sdkStaleIsReported proves that the Go SDK's staleness check can fail. It runs
// that check against a bare module — the same probeModuleSource the sweep's proof
// uses — once as the SDK generated it, where it must pass, and once with its
// bindings made stale, where it must fail.
//
// The pristine half is what makes the stale half mean something: a check that
// failed on a module that was never valid would satisfy "it failed" for a reason
// that has nothing to do with the tampering.
//
// The probe is built *in* ws, not in a workspace made from a Directory, so the
// SDK module resolves the way it does for the leg that runs the real check: from
// the same reference, through the same dagger.lock. Its config is replaced with
// one that installs only the SDK and manages only the probe, because the
// staleness check regenerates every module its SDK manages, and the proof is
// meant to cost seconds rather than a second full sweep. Workspace.with* returns
// a new workspace and writes nothing to the caller's checkout.
func sdkStaleIsReported(ctx context.Context, ws *dagger.Workspace, sdk *dagger.WorkspaceSDK, pin string) error {
	ref, err := sdk.Ref(ctx)
	if err != nil {
		return fmt.Errorf("stale-module proof: read the %s SDK's module reference: %w", probeSDK, err)
	}
	// The staleness check belongs to the module the SDK was installed from, under
	// whatever name the workspace installed it as.
	installed, err := ws.Modules(ctx)
	if err != nil {
		return fmt.Errorf("stale-module proof: list the modules the workspace installs: %w", err)
	}
	module := ""
	for i := range installed {
		src, err := installed[i].Source(ctx)
		if err != nil {
			return fmt.Errorf("stale-module proof: read an installed module's source: %w", err)
		}
		if src == ref {
			if module, err = installed[i].Name(ctx); err != nil {
				return fmt.Errorf("stale-module proof: read the name of the module %q: %w", ref, err)
			}
			break
		}
	}
	if module == "" {
		return fmt.Errorf("stale-module proof: no installed module is the %s SDK's own %q", probeSDK, ref)
	}

	cwd, err := ws.Cwd(ctx)
	if err != nil {
		return fmt.Errorf("stale-module proof: read the workspace's current directory: %w", err)
	}
	configFile, err := ws.ConfigFile(ctx)
	if err != nil {
		return fmt.Errorf("stale-module proof: find the workspace's config file: %w", err)
	}

	suffix, err := uniqueSuffix()
	if err != nil {
		return err
	}
	dir := ".workspace-ci-generated-probe-" + suffix
	config := fmt.Sprintf("[modules.%q]\nsource = %q\n\n[sdks.%q]\nmodule = %q\n\n[sdks.%q.scopes.%q]\nis-module = true\n",
		module, ref, probeSDK, module, probeSDK, dir)
	manifest := fmt.Sprintf("name = \"generated-probe\"\nengineVersion = %q\n\n[runtime]\n  source = %q\n\n[codegen]\n  automaticGitignore = false\n",
		pin, probeSDK)
	src := dag.Directory().
		WithNewFile("dagger-module.toml", manifest).
		WithNewFile("main.go", probeModuleSource)

	// The config is replaced where the workspace reads it from, which ConfigFile
	// reports relative to the workspace's current directory.
	probe := ws.
		WithNewFile(path.Join(cwd, configFile), config).
		WithNewDirectory("/"+dir, src)
	pristine := probe.WithChanges(probe.SDK(probeSDK).Generate())
	staleFile := "/" + dir + "/" + probeStaleFile
	contents, err := pristine.File(staleFile).Contents(ctx)
	if err != nil {
		return fmt.Errorf("stale-module proof: generate the probe module: %w", err)
	}
	stale := pristine.WithNewFile(staleFile, contents+"\n// workspace-ci: deliberately stale\n")

	var clean, drifted []string
	g, gctx := errgroup.WithContext(ctx)
	g.Go(func() (err error) {
		clean, err = failingChecks(gctx, pristine, module)
		return err
	})
	g.Go(func() (err error) {
		drifted, err = failingChecks(gctx, stale, module)
		return err
	})
	if err := g.Wait(); err != nil {
		return fmt.Errorf("stale-module proof: %w", err)
	}
	if len(clean) > 0 {
		return fmt.Errorf("stale-module proof: the %s SDK's checks fail on a module it just generated, so their failing proves nothing:\n  %s", probeSDK, strings.Join(clean, "\n  "))
	}
	if len(drifted) == 0 {
		return fmt.Errorf("stale-module proof: a module with deliberately stale bindings passed every check of %q, so a green staleness check verifies nothing", module)
	}
	return nil
}

// failingChecks runs every check module declares in ws and returns one line for
// each that fails. A module that declares no checks is an error: there is then
// nothing whose failing could prove anything.
func failingChecks(ctx context.Context, ws *dagger.Workspace, module string) ([]string, error) {
	checks, err := ws.Artifacts(dagger.WorkspaceArtifactsOpts{Include: []string{module}}).
		FilterTypes([]string{"Check"}).
		AsChecks(ctx)
	if err != nil {
		return nil, fmt.Errorf("list the checks of %q: %w", module, err)
	}
	if len(checks) == 0 {
		return nil, fmt.Errorf("%q declares no checks", module)
	}
	var failed []string
	for i := range checks {
		// Error is selected once and Message read off that result: selecting Error
		// twice would run the check twice.
		failure, err := checks[i].Error(ctx)
		if err != nil {
			return nil, fmt.Errorf("run a check of %q: %w", module, err)
		}
		if failure == nil {
			continue
		}
		msg, err := failure.Message(ctx)
		if err != nil {
			return nil, fmt.Errorf("read a failing check's message: %w", err)
		}
		failed = append(failed, msg)
	}
	return failed, nil
}
